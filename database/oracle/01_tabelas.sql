-- 01_tabelas.sql
-- Cria a estrutura do banco (DDL). Rode conectado como o usuario PEDIDOS.
-- No DBeaver: abra este arquivo e execute como script (Alt+X).
--
-- Em empresas que usam Oracle, normalmente quem cria as tabelas sao
-- scripts versionados como este (ou o DBA), e nao o Hibernate.
-- Por isso a aplicacao usa spring.jpa.hibernate.ddl-auto=none.
-- =====================================================================

-- "IF EXISTS" funciona no Oracle 23ai (versao da imagem Docker oracle-free).
-- Permite rodar o script de novo do zero sem dar erro.
DROP TABLE IF EXISTS log_pedidos   CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS itens_pedido  CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS pedidos       CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS produtos      CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS categorias    CASCADE CONSTRAINTS;

-- ---------------------------------------------------------------------
-- CATEGORIAS
-- GENERATED BY DEFAULT AS IDENTITY = auto incremento (Oracle 12c+).
-- Antes do 12c o padrao era SEQUENCE + TRIGGER (bom saber pra entrevista).
-- ---------------------------------------------------------------------
CREATE TABLE categorias (
    id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome  VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_categorias      PRIMARY KEY (id),
    CONSTRAINT uk_categorias_nome UNIQUE (nome)
);

-- ---------------------------------------------------------------------
-- PRODUTOS
-- NUMBER(10,2): ate 10 digitos, 2 casas decimais. Dinheiro NUNCA em float.
-- No Java isso vira BigDecimal.
-- ---------------------------------------------------------------------
CREATE TABLE produtos (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR2(150) NOT NULL,
    valor         NUMBER(10,2)  NOT NULL,
    estoque       NUMBER(10)    DEFAULT 0 NOT NULL,
    categoria_id  NUMBER,
    CONSTRAINT pk_produtos           PRIMARY KEY (id),
    CONSTRAINT uk_produtos_nome      UNIQUE (nome),
    CONSTRAINT ck_produtos_valor     CHECK (valor > 0),
    CONSTRAINT ck_produtos_estoque   CHECK (estoque >= 0),
    CONSTRAINT fk_produtos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id)
);

-- ---------------------------------------------------------------------
-- PEDIDOS
-- O status so pode assumir 3 valores (CHECK constraint).
-- ---------------------------------------------------------------------
CREATE TABLE pedidos (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    cliente      VARCHAR2(150) NOT NULL,
    data_pedido  DATE          DEFAULT SYSDATE NOT NULL,
    status       VARCHAR2(20)  DEFAULT 'ABERTO' NOT NULL,
    valor_total  NUMBER(12,2)  DEFAULT 0 NOT NULL,
    CONSTRAINT pk_pedidos        PRIMARY KEY (id),
    CONSTRAINT ck_pedidos_status CHECK (status IN ('ABERTO', 'FINALIZADO', 'CANCELADO'))
);

-- ---------------------------------------------------------------------
-- ITENS_PEDIDO
-- valor_unitario guarda o preco do produto NO MOMENTO da compra.
-- Se o preco do produto mudar depois, o pedido antigo nao muda.
-- ---------------------------------------------------------------------
CREATE TABLE itens_pedido (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    pedido_id       NUMBER       NOT NULL,
    produto_id      NUMBER       NOT NULL,
    quantidade      NUMBER(10)   NOT NULL,
    valor_unitario  NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_itens_pedido     PRIMARY KEY (id),
    CONSTRAINT ck_itens_quantidade CHECK (quantidade > 0),
    CONSTRAINT fk_itens_pedido     FOREIGN KEY (pedido_id)  REFERENCES pedidos (id),
    CONSTRAINT fk_itens_produto    FOREIGN KEY (produto_id) REFERENCES produtos (id)
);

-- Indice na FK: acelera "buscar itens do pedido X" e evita lock de tabela inteira
-- ao apagar/alterar pedidos. Classico de entrevista Oracle.
CREATE INDEX ix_itens_pedido_pedido ON itens_pedido (pedido_id);
CREATE INDEX ix_pedidos_cliente     ON pedidos (cliente);

-- ---------------------------------------------------------------------
-- LOG_PEDIDOS
-- Usada pelo package com PRAGMA AUTONOMOUS_TRANSACTION:
-- o log e gravado mesmo quando a operacao principal da ROLLBACK.
-- ---------------------------------------------------------------------
CREATE TABLE log_pedidos (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    pedido_id  NUMBER,
    acao       VARCHAR2(50)   NOT NULL,
    mensagem   VARCHAR2(4000),
    data_log   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_log_pedidos PRIMARY KEY (id)
);
